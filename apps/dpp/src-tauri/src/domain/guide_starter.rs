//! The legal guide's starter offences for Uganda: what each one needs proved,
//! the papers it usually rests on, and what is often missing.
//!
//! Source of the law: the Penal Code Act, Cap. 120 (the numbering Ugandan
//! charge sheets use today), read from the Act's own text on WIPO Lex on
//! 2026-11-25. "Proving" lines are the Act's elements in plain words, each with
//! the section they come from. "Papers" and "gaps" are practice, written from
//! those elements: they are a starting draft for the office to correct, never
//! the law. The ULII 2024 revised edition renumbers these sections; this file
//! follows Cap. 120 until the office says otherwise. Research notes:
//! docs/dpp/research/penal-code-elements-2026-11-25.md

